/**
 * ESLint for the whole workspace — `apps/api`, `apps/web` and
 * `packages/esquemas` from one root config, the same way `pnpm -r` runs one
 * `test` and one `typecheck`.
 *
 * Two things this config deliberately is NOT:
 *
 * 1. **Not a formatter.** No Prettier, no `eslint-config-prettier`, and not a
 *    single rule about quotes, semicolons, trailing commas, indentation or
 *    line width. Reformatting ~34k lines would bury every real finding under
 *    whitespace churn. `tsc` and this config check correctness; the diff of
 *    an actual change stays readable.
 *
 * 2. **Not a wall of warnings.** Every rule below is `error`, and `pnpm lint`
 *    runs with `--max-warnings 0`. A lint job that is allowed to be yellow
 *    teaches people that yellow is normal, and then it stops being read at
 *    all. If a rule cannot pass honestly today it is listed in DEFERRED
 *    below with its finding count and left OFF — never downgraded to `warn`,
 *    never silenced with a blanket `eslint-disable`, and never hidden behind
 *    an `ignores` entry that quietly drops real source.
 *
 * Conventions this codebase owns, which the config must not fight:
 *
 * - **Identifiers are Spanish** (`buscarContrato`, `PropiedadesEnvioDeFirma`,
 *   `nombreCompleto`) — see CLAUDE.md and DESIGN.md. No `naming-convention`
 *   rule is enabled, and none ever should be: every one of them assumes
 *   English. This also breaks `react-hooks/rules-of-hooks`; see DEFERRED.
 * - **Hexagonal/screaming architecture.** Exported `PropiedadesX`, `ComandoX`,
 *   `DatosX` and `FilaX` types are public surface on purpose, even when the
 *   only current consumer is their own file. Nothing here flags them.
 * - **NestJS decorators.** `experimentalDecorators`/`emitDecoratorMetadata`
 *   come from each package's own tsconfig, which the type-aware setup below
 *   reads directly — so decorator and parameter-injection semantics are the
 *   ones `tsc` uses, not a re-declared approximation.
 * - **Vitest, not Jest.** Specs are `*.spec.ts`/`*.spec.tsx` colocated with
 *   their source, and are linted exactly like the source beside them: there
 *   is no per-rule relaxation for test files anywhere in this config.
 */
